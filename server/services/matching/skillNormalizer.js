/**
 * Escapes regex special characters in a string.
 */
export const escapeRegExp = (str = "") => {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
};

/**
 * Normalizes a raw skill string into its canonical representation.
 * If no alias matches, cleans up whitespace and returns title case.
 */
export const normalizeSkill = (rawSkill = "") => {
  if (!rawSkill || typeof rawSkill !== "string") return "";
  const cleaned = rawSkill.trim().toLowerCase().replace(/['"]/g, "");

  if (SKILL_ALIASES[cleaned]) {
    return SKILL_ALIASES[cleaned];
  }

  // Remove common trailing words like "framework", "library", "technology", "development"
  const stripped = cleaned
    .replace(
      /\s+(framework|library|technologies|technology|skills|skill|development|developer|stack)$/i,
      ""
    )
    .trim();

  if (SKILL_ALIASES[stripped]) {
    return SKILL_ALIASES[stripped];
  }

  // Title-case fallback
  return rawSkill
    .trim()
    .split(/\s+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(" ");
};

/**
 * Builds a safe, precise regular expression for matching a skill or alias in text.
 * Prevents false positives (e.g. Java vs JavaScript, Go vs normal English, C vs letter C).
 */
export const getSkillRegexPattern = (alias = "") => {
  const clean = alias.trim().toLowerCase();
  if (!clean) return null;

  // 1. Strict guards for short / highly ambiguous terms
  if (clean === "go") {
    // Matches Golang phrases or standalone 'Go' in tech contexts / skill lists
    return /(?:(?<=\b(?:skills|technologies|languages|tech stack|proficiencies|stack)\s*:[^\n]*)\bgo\b|\bgo\s*[,/|]\s*(?:python|rust|c\+\+|java|c#|node|ruby|php|ts|js|sql|kotlin|scala)\b|\b(?:python|rust|c\+\+|java|c#|node|ruby|php|ts|js|sql|kotlin|scala)\s*[,/|]\s*go\b|\bgo\s+(?:developer|engineer|backend|programming|runtime)\b)/i;
  }

  if (clean === "c") {
    // Matches C programming, ANSI C, Embedded C, or C in a languages list / next to C++
    return /(?:(?<=\b(?:skills|technologies|languages|tech stack|proficiencies|stack)\s*:[^\n]*)\bc\b|\bc\s*[\/,|]\s*c\+\+\b|\bc\+\+\s*[\/,|]\s*c\b|\bc\s*,\s*(?:java|python|c\+\+|c#|rust|go)\b|\b(?:java|python|c\+\+|c#|rust|go)\s*,\s*c\b|\b(?:ansi\s+c|embedded\s+c|c\s+(?:language|programming|developer|engineer))\b)/i;
  }

  if (clean === "r") {
    // Matches R language / programming or next to Python
    return /(?:(?<=\b(?:skills|technologies|languages|tech stack|proficiencies)\s*:[^\n]*)\br\b|\br\s*[\/,|]\s*python\b|\bpython\s*[\/,|]\s*r\b|\br\s+(?:language|programming|package|scripting)\b)/i;
  }

  if (clean === "rest" || clean === "restful") {
    return /(?<![a-zA-Z0-9_#+])(?:rest\s*api[s]?|restful(?:\s*api[s]?)?|restful\s+services|rest\s+endpoints|rest\s+architecture|(?<=\b(?:skills|technologies|stack)\s*:[^\n]*)\brest\b)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "js") {
    // Standalone JS, but not .js from Node.js, Next.js, script.js
    return /(?<![a-zA-Z0-9_#+.])js(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "ts") {
    // Matches 'TS' in tech stack context (e.g. JS/TS, or Skills: React, TS, Node)
    return /(?:\b(?:js\s*[\/,|]\s*ts|ts\s*[\/,|]\s*js)\b|(?<=\b(?:skills|technologies|languages|tech stack|stack|proficiencies)\s*:[^\n]*)(?<![a-zA-Z0-9_#+.])ts(?![a-zA-Z0-9_#+])|\btypescript\b)/i;
  }

  if (clean === "react") {
    // Must match React, ReactJS, React.js but NOT React Native
    return /(?<![a-zA-Z0-9_#+])react(?:\.js|js)?(?!\s*[-]?\s*native)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "react native" || clean === "react-native") {
    return /(?<![a-zA-Z0-9_#+])react\s*[-]?\s*native(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "node" || clean === "nodejs" || clean === "node.js" || clean === "node js") {
    return /(?<![a-zA-Z0-9_#+])(?:node\.js|nodejs|node\s+js|node\b(?!\s*[-]?\s*(?:module|modules|red|element|elements|dom|graph|tree|cluster|point)))(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "webrtc" || clean === "web rtc" || clean === "web-rtc") {
    return /(?<![a-zA-Z0-9_#+])web[\s-]?rtc(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "socket.io" || clean === "socketio") {
    return /(?<![a-zA-Z0-9_#+])(?:socket\.io|socketio)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "c++" || clean === "cpp") {
    return /(?<![a-zA-Z0-9_#+])(?:c\+\+|cpp)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "c#" || clean === "csharp" || clean === "c-sharp") {
    return /(?<![a-zA-Z0-9_#+])(?:c#|csharp|c-sharp)(?!\s*[\d]+)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === ".net core" || clean === "asp.net" || clean === "asp.net core" || clean === "dotnet") {
    return /(?<![a-zA-Z0-9_#+])(?:asp\.net(?:\s+core)?|\.net\s+core|dotnet)(?![a-zA-Z0-9_#+])/i;
  }

  if (clean === "ci/cd" || clean === "cicd") {
    return /(?<![a-zA-Z0-9_#+])(?:ci\/cd|cicd)(?![a-zA-Z0-9_#+])/i;
  }

  // 2. Standard Safe Boundary Check for general skills
  // Uses negative lookbehind/lookahead to safely handle dots, slashes, numbers
  const escaped = escapeRegExp(clean);
  return new RegExp(`(?<![a-zA-Z0-9_#+])${escaped}(?![a-zA-Z0-9_#+])`, "i");
};

/**
 * Collects all aliases that normalize to the same canonical skill.
 */
export const getAliasesForSkill = (skill = "") => {
  if (!skill) return [];
  const canonical = normalizeSkill(skill);
  const aliases = new Set([skill.toLowerCase().trim(), canonical.toLowerCase().trim()]);

  for (const [alias, mappedCanonical] of Object.entries(SKILL_ALIASES)) {
    if (mappedCanonical.toLowerCase() === canonical.toLowerCase()) {
      aliases.add(alias);
    }
  }

  return Array.from(aliases);
};

/**
 * Checks if candidate skill matches required job skill.
 * Strictly verifies identity or canonical alias without hallucinating relationships!
 */
export const isSkillMatch = (candidateSkill, requiredSkill) => {
  if (!candidateSkill || !requiredSkill) return false;

  const normCandidate = normalizeSkill(candidateSkill).toLowerCase();
  const normRequired = normalizeSkill(requiredSkill).toLowerCase();

  if (normCandidate === normRequired) return true;

  const rawCand = candidateSkill.toLowerCase().trim();
  const rawReq = requiredSkill.toLowerCase().trim();

  if (rawCand === rawReq) return true;

  if (
    rawCand.includes("rest") &&
    rawReq.includes("rest") &&
    rawCand.includes("api") &&
    rawReq.includes("api")
  ) {
    return true;
  }

  if (
    (rawCand.includes("node") && rawReq.includes("node")) ||
    (rawCand.includes("react") &&
      rawReq.includes("react") &&
      !rawCand.includes("native") &&
      !rawReq.includes("native")) ||
    (rawCand.includes("mongo") && rawReq.includes("mongo")) ||
    (rawCand.includes("express") && rawReq.includes("express")) ||
    (rawCand.includes("postgre") && rawReq.includes("postgre")) ||
    (rawCand.includes("tailwind") && rawReq.includes("tailwind")) ||
    (rawCand.includes("typescript") && rawReq.includes("typescript")) ||
    (rawCand.includes("javascript") && rawReq.includes("javascript"))
  ) {
    return true;
  }

  return false;
};

/**
 * Normalizes an array of skills, filtering duplicates.
 */
export const normalizeSkillList = (skills = []) => {
  const seen = new Set();
  const result = [];

  for (const s of skills) {
    if (!s) continue;
    const name = typeof s === "string" ? s : s.skill || s.name || "";
    const norm = normalizeSkill(name);
    const key = norm.toLowerCase();
    if (norm && !seen.has(key)) {
      seen.add(key);
      result.push(norm);
    }
  }

  return result;
};

/**
 * Checks if a specific skill (or any of its known aliases) is explicitly mentioned in resume text.
 * Strictly verifies against actual text and avoids false positives.
 */
export const isSkillExplicitlyPresent = (skill = "", resumeText = "") => {
  if (!skill || !resumeText || typeof resumeText !== "string") return false;

  const aliases = getAliasesForSkill(skill);

  for (const alias of aliases) {
    const pattern = getSkillRegexPattern(alias);
    if (pattern && pattern.test(resumeText)) {
      return true;
    }
  }

  return false;
};

/**
 * Cleans up and trims an extracted line/snippet for evidence presentation.
 */
const cleanEvidenceSnippet = (line = "") => {
  if (!line) return "";
  let clean = line
    .replace(/^[\s•\-\*–—\d\.\)\:]+/, "") // remove leading bullet points, numbers
    .replace(/\s+/g, " ")
    .trim();

  if (clean.length > 180) {
    clean = clean.slice(0, 177) + "...";
  }

  return clean;
};

/**
 * Determines the strength ("High" vs "Medium") based on evidence line context.
 */
const determineEvidenceStrength = (snippet = "") => {
  const lower = snippet.toLowerCase();
  const highActionVerbs = [
    "developed",
    "built",
    "implemented",
    "created",
    "designed",
    "engineered",
    "architected",
    "deployed",
    "scaled",
    "optimized",
    "configured",
    "integrated",
    "managed",
    "led",
    "migrated",
    "refactored",
    "automated",
  ];

  for (const verb of highActionVerbs) {
    if (new RegExp(`\\b${verb}\\b`, "i").test(lower)) {
      return "High";
    }
  }

  return "Medium";
};

/**
 * Finds the exact line/sentence evidence in resume text for a given skill.
 * Returns null if the skill does not explicitly occur in resumeText.
 */
export const findSkillEvidence = (skill = "", resumeText = "") => {
  if (!skill || !resumeText || typeof resumeText !== "string") return null;

  const canonical = normalizeSkill(skill);
  const aliases = getAliasesForSkill(skill);
  const lines = resumeText
    .split(/[\r\n]+/)
    .map((l) => l.trim())
    .filter(Boolean);

  for (const alias of aliases) {
    const pattern = getSkillRegexPattern(alias);
    if (!pattern) continue;

    for (const line of lines) {
      if (pattern.test(line)) {
        const snippet = cleanEvidenceSnippet(line);
        const strength = determineEvidenceStrength(line);
        return {
          found: true,
          skill: canonical,
          matchedAlias: alias,
          evidence: snippet || line,
          strength,
          confidence: strength === "High" ? 0.98 : 0.95,
        };
      }
    }
  }

  return null;
};

/**
 * Deterministically extracts all explicitly mentioned skills from raw resume text.
 * - Inspects resume text against canonical skill registry and all known aliases.
 * - Extracts ONLY skills with direct textual evidence.
 * - Normalizes to canonical skill names.
 * - Deduplicates by canonical name.
 * - Returns structured skill evidence objects with real snippet evidence.
 */
export const extractExplicitSkillsFromResume = (resumeText = "") => {
  if (
    !resumeText ||
    typeof resumeText !== "string" ||
    !resumeText.trim() ||
    resumeText.startsWith("%PDF") ||
    /[\x00-\x08\x0E-\x1F]/.test(resumeText.slice(0, 100))
  ) {
    return [];
  }

  const lines = resumeText
    .split(/[\r\n]+/)
    .map((l) => l.trim())
    .filter(Boolean);

  const resultMap = new Map();

  // 1. Collect all unique canonical skills and their alias lists
  const canonicalToAliases = new Map();
  for (const [alias, canonical] of Object.entries(SKILL_ALIASES)) {
    if (!canonicalToAliases.has(canonical)) {
      canonicalToAliases.set(canonical, new Set([canonical.toLowerCase()]));
    }
    canonicalToAliases.get(canonical).add(alias);
  }

  // 2. Scan lines for each canonical skill and its aliases
  for (const [canonical, aliasesSet] of canonicalToAliases.entries()) {
    for (const alias of aliasesSet) {
      const pattern = getSkillRegexPattern(alias);
      if (!pattern) continue;

      for (const line of lines) {
        if (pattern.test(line)) {
          const key = canonical.toLowerCase();
          const strength = determineEvidenceStrength(line);
          const snippet = cleanEvidenceSnippet(line);
          const confidence = strength === "High" ? 0.98 : 0.95;

          const existing = resultMap.get(key);
          if (!existing || (strength === "High" && existing.strength !== "High")) {
            resultMap.set(key, {
              skill: canonical,
              evidence: snippet || line,
              source: "resume",
              confidence,
              strength,
            });
          }
          break; // move to next canonical once matched or checking better strength
        }
      }
    }
  }

  return Array.from(resultMap.values());
};
